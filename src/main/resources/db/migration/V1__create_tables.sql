-- a named collection of rules
CREATE TABLE rule_sets (
    -- auto-incrementing primary key
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- create index and reject duplicate names (UNIQUE)
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL
);

-- rules of a rule set
CREATE TABLE rules (
    -- Primary key
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Foreign key, cascade deleting a rule set to delete its rules
    rule_set_id BIGINT NOT NULL REFERENCES rule_sets (id) ON DELETE CASCADE,
    column_name VARCHAR(100) NOT NULL,
    -- rule types: REQUIRED, DATA_TYPE, RANGE, ALLOWED_VALUES, REGEX, UNIQUE
    rule_type VARCHAR(30) NOT NULL,
    -- optional parameters
    data_type VARCHAR(20)
    min_value NUMERIC(19, 4),
    max_value NUMERIC(19, 4),
    pattern VARCHAR(500),
    allowed_values VARCHAR(1000)
);

-- foreign keys aren't indexed, so index rules by rule set
CREATE INDEX idx_rules_rule_set_id ON rules (rule_set_id);

-- one upload-and-validate event
CREATE TABLE validation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_set_id BIGINT NOT NULL REFERENCES rule_sets (id) ON DELETE CASCADE,
    filename VARCHAR(255) NOT NULL,
    total_rows INTEGER NOT NULL,
    -- number of rows with at least one error
    failed_rows INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX index_validation_runs_rule_set_id ON validation_runs (rule_set_id);

-- one failed check on one cell of the uploaded file
CREATE TABLE row_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES validation_runs (id) ON DELETE CASCADE,
    row_number INTEGER NOT NULL,
    column_name VARCHAR(100) NOT NULL,
    rule_type VARCHAR(30) NOT NULL,
    message VARCHAR(500) NOT NULL
)
-- find a run's errors and return them ordered by row number
CREATE INDEX idx_row_errors_run_row ON row_errors (run_id, row_number);